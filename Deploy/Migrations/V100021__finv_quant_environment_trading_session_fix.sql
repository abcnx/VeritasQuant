-- =====================================================================
-- FinvQuant PostgreSQL V100021：修正默认 COMEX 黄金回测环境交易时段
--
-- 背景（ACANX 2026-08-06 实测反馈）：
--   GCMain 黄金期货主连行情为全天 24 小时电子盘（time 0~235900），
--   而默认环境 ENV-BT-COMEX-GC 的 trading_sessions 仅配置 08:20-13:30，
--   导致约 77% 的活跃行情 bar 被判定为「不在环境交易时段内」而拒单。
--
-- 修正：将该环境交易时段覆盖为全天（000000-235959），
--   「行情在、即可交易」，消除非时段误拒。用户如需限制主力时段，
--   可在「环境与模板管理」中按需改回窄时段（拒绝原因已明确化）。
--
-- 幂等：仅更新 ENV-BT-COMEX-GC，其余环境不受影响。
-- =====================================================================

UPDATE finv_quant_environment
SET config = jsonb_set(config, '{trading_sessions}',
  '[{"start":"000000","end":"235959"}]'::jsonb, false)
WHERE env_code = 'ENV-BT-COMEX-GC';

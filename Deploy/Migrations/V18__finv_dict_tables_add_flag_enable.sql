-- =====================================================================
-- FinvQuant PostgreSQL V18：finv_exchange / finv_market / finv_security
-- 三张核心字典表统一增加 flag_enable 启用标志
--
-- 决策（ACANX 2026-08-05）：
--   - "元数据管理"菜单下的交易所信息维护 / 交易所下设市场信息维护 /
--     规范证券信息维护 三个子菜单提供"禁用/启用"维护能力，
--     三张字典表需要启用标志字段支撑；
--   - 类型 CHAR(1)，默认值字符 '0'（0=禁用，1=启用；程序层按需 UPDATE 切换）；
--   - ADD COLUMN IF NOT EXISTS 幂等，重复执行不报错；
--   - 与 V17（映射表 flag_enable）风格一致：单事务、失败回滚。
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. 交易所/市场字典表
-- ---------------------------------------------------------------------
ALTER TABLE finv_exchange
    ADD COLUMN IF NOT EXISTS flag_enable CHAR(1) NOT NULL DEFAULT '0';

-- ---------------------------------------------------------------------
-- 2. 交易市场表
-- ---------------------------------------------------------------------
ALTER TABLE finv_market
    ADD COLUMN IF NOT EXISTS flag_enable CHAR(1) NOT NULL DEFAULT '0';

-- ---------------------------------------------------------------------
-- 3. 证券代码表
-- ---------------------------------------------------------------------
ALTER TABLE finv_security
    ADD COLUMN IF NOT EXISTS flag_enable CHAR(1) NOT NULL DEFAULT '0';

COMMIT;
